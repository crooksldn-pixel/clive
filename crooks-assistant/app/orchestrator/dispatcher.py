"""Engineering Dispatcher V1: a deterministic controller around the frozen kernel.

It coordinates; it does not reason. Each ``tick`` reads the authoritative records,
finds the one transition each objective is eligible for, performs or reconciles
the execution behind it, and submits what actually happened to the kernel:

    READY            -> fresh workspace at the base, ``assign``, launch the builder (a
                        build revision whose scope lacks a file its base declares as
                        generated first becomes a revision that has it: "Generated files")
    ASSIGNED         -> the worker's own init event, checked against the launch
                        policy, is the acknowledgement (``ack``); a bad roster blocks
    RUNNING          -> stream events renew the lease (``heartbeat``); a successful
                        file edit is ``progress``; the worker's result is committed by
                        CLIVE, its generated files regenerated by the loop, scoped,
                        checked in the sandbox (``checks.py``), recorded as ``evidence``
                        and the exact git SHA as the ``candidate``
    EVIDENCE_READY   -> once GitHub's ``acceptance`` run is green on the exact candidate
                        SHA (``github_acceptance.py``), an independent, available reviewer
                        gets the exact-SHA packet (``dispatch``); if none is available, the
                        task is BLOCKED with the exact gap, and nothing is dispatched to nobody;
                        a red run routes a repair revision ("A red run is a repair round")
    REVIEWING        -> a typed ``clive.review_result.v1`` is submitted (``verdict``);
                        the kernel admits, rejects or refuses it; a READY verdict is
                        submitted only while the candidate SHA is green on GitHub
    REJECTED         -> a repair revision carrying the material findings (``task``
                        r+1, kind repair); after ``max_repair_rounds`` it blocks
    ACCEPTED         -> the accepted SHA is green on GitHub and the target ref is
                        verified at it (``integrate``, fast-forward only)
    DONE             -> COMPLETE when the projection says every record agrees; then the
                        loop lands it on ``clive/trunk``, or refreshes it onto a trunk that
                        moved (``task`` r+1, kind integration): "Landing"
    BLOCKED / OWNER_GATE -> nothing; the dispatcher never lifts either (the one block it
                        acts on is its own first half of routing a repair from a red run,
                        ``RED_REPAIR``, which it completes by the revision that supersedes it)

The GitHub acceptance gate (owner's loop update, OWNER_DECISIONS_2026-09-25.md): an
objective counts as accepted, and anything is integrated, only after a green GitHub
acceptance run on that exact SHA. Waiting is bounded: the gate is asked at most every
``acceptance_poll_s``, and a step that has waited ``acceptance_timeout_s`` for its SHA to
turn green (counted again from the task's last resume) blocks the task with the last
answer; a red answer blocks at once. Every answer is recorded with the SHA it is about
(``<runtime>/attempts/<attempt>.json`` and ``<runtime>/evidence/<attempt>/github-acceptance.json``),
travels in the review packet, is the integration's ``gates_evidence`` (kept byte for byte in
``<runtime>/evidence/<attempt>/integration-gates.json``), and is published by the remote loop's
status projection. The kernel CLI gates and records the verdicts and integrations an operator
records by hand in the same way (``scripts/engineering_kernel.py``). The loop never publishes a candidate onto the
trunk (``landing_branches``): an objective's candidate lives on its own branch, and the
trunk moves only by a landing made after acceptance (below, or the Director's).

Generated files are the loop's job, not the builder's (OWNER_DECISIONS_2026-09-30, "go"). The
repository declares its generators in ``crooks-assistant/config/generated_files.json`` (``generated.py``),
a protected path, read at the task's base commit and never from the candidate. After a builder
reports and before CLIVE's own checks run, each declared generator runs inside the check sandbox
on a fresh export of the candidate; a declared output it changed is committed onto the candidate
branch as the loop's own commit ("Regenerate generated files (loop)"), and that commit is the SHA
everything after sees. A change the generator made to any other file is discarded and blocks the
task; a declared output is never a protected path. A declared output may lie outside the
objective's own scope because the loop wrote it, and only then: the kernel reviews a candidate
only inside its task's scope, so a build revision gains exactly those outputs as a revision of its
own before its first attempt, and the dispatcher accepts such a path in a candidate only as exactly
the generator's output on that candidate (a builder's own edit of it is replaced by the generator's).

A red run is a repair round (OWNER_DECISIONS_2026-09-30, "go"): a red answer at review dispatch
routes a repair revision, the same way a CHANGES_REQUIRED verdict does, carrying what failed (the
failing tests, the failing assertion lines and a redacted tail of the failed job's log, fetched
through the gate's ``failure_log``; or, when no log can be read, the run, job and step names and
that fact). Review and GitHub repairs share ``max_repair_rounds``; once they are used, a red run
blocks as before, with its last failure. A repair is a new SHA made by a builder: nothing is re-run
to turn green. Integration and landing ask afresh and refuse red, unchanged.

Landing (OWNER_DECISIONS_2026-09-30, "the loop lands its own work"; ``DispatcherConfig.land``,
off with ``--no-land``, which leaves the loop exactly as it was). An objective the loop integrated
while landing was on is fast-forwarded onto ``clive/trunk`` at exactly its integrated SHA, at most
once per tick, only when (a) GitHub acceptance is green on that SHA, asked at that moment; (b) the
kernel accepted the loop's READY review of that SHA and integrated it fast-forward; (c) the diff
from the trunk head to it touches no protected path; (d) it contains the trunk head, so the push is
a plain push (never forced) that git refuses if the trunk moved; the remote trunk is then verified
at the SHA. The intent is recorded before the push and the landing after it
(``<runtime>/landings/<objective>.json``, ``<runtime>/evidence/<attempt>/landing.json``), so a restart
between the two records it without pushing again. If the trunk moved, the loop merges it into the
objective's branch: a revision of kind integration, run by the integrator in a fresh workspace, whose
merge commit gets its generated files, checks, green run and READY review of its own before it may
land; a conflict blocks it for the Director, and refreshes are bounded (``max_landing_refreshes``).

Protected paths: a task whose scope covers a PROTECTED_PATHS entry (possible only for an
objective recorded before that entry was added) is blocked before it can advance, its
worker stopped first if one is assigned or running, and a candidate that changes a
protected path is refused whatever the task's scope says.

What it never does: manufacture a state (a launch is not an acknowledgement, a
live process is not progress, a worker's "done" is not a candidate, a candidate is
not accepted, an acceptance is not an integration, an integration is not a
deployment), lift an owner gate, deploy, or touch anything outside the task's
workspace, its candidate refs and its target branch.

Restart: every stage is re-derived from the kernel's records on each tick; the
dispatcher's own runtime notes (``<runtime>/attempts/*.json``) hold only execution
facts (pid, launch time, how many worker events were already mapped). Worker
processes are found on the host by their attempt marker, so a restarted
dispatcher re-attaches instead of launching a second worker, and a worker that
finished while the dispatcher was down is ingested from its log and workspace.

Failure classes: a transient failure (a provider error, a process that died, a
stall) cancels the attempt and retries with exponential backoff, at most
``max_transient_retries`` times, counted from the kernel's cancellation records; a
deterministic failure (a refused launch surface, missing capability, a worker that
reports it is blocked, a candidate that cannot be published) blocks the task once.

Stopping a worker is confirmed (the 2026-09-30 re-pin review, F-01): wherever the
dispatcher stops one (a stall, no init in time, a refused launch surface, an expired lease,
a protected scope, the attempt time limit, after its result, any cancel), the driver's
``kill`` sends SIGTERM, waits (bounded), sends SIGKILL to what remains and waits again, and
the cancel or block is recorded as a stop only once no process of the attempt is alive
(``_stop``). A worker that cannot be stopped blocks the task with a reason that says so and
names the attempt; it is never recorded as a normal cancel.
"""

